<?php

use Illuminate\Support\Facades\Broadcast;

/*
|--------------------------------------------------------------------------
| Broadcast Channels
|--------------------------------------------------------------------------
| تفويض قنوات البث الخاصة. قناة الشات private-chat.{userId} يستقبل عليها
| المستخدم رسائله الواردة (NewMessage يبث على قناة المستقبِل) — لذلك لا
| يُسمح بالاشتراك فيها إلا لصاحب الـ id نفسه. أي مستخدم آخر يُرفض اشتراكه،
| فلا يمكن التنصّت على رسائل الآخرين.
*/

Broadcast::channel('chat.{userId}', function ($user, int $userId) {
    return (int) $user->id === $userId;
});
