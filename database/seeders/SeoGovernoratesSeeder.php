    public function run(): void
    {
        $this->command->info('🌍 بدء زرع بيانات SEO لمحافظات مصر...');

        $governoratesData = $this->governoratesData();
        $inserted         = 0;
        $skipped          = 0;
        $errors           = [];

        foreach ($governoratesData as $govData) {
            try {
                // جلب المحافظة من قاعدة البيانات باستخدام الـ slug
                $location = Location::where('slug', $govData['slug'])
                    ->where('level', Location::LEVEL_GOVERNORATE)
                    ->first();

                if (! $location) {
                    // محاولة بديلة: البحث باسم المحافظة العربي
                    $location = Location::where('name_ar', $govData['name_ar'])
                        ->where('level', Location::LEVEL_GOVERNORATE)
                        ->first();
                }

                if (! $location) {
                    $skipped++;
                    $errors[] = "⚠️  المحافظة غير موجودة في قاعدة البيانات: {$govData['name_ar']} (slug: {$govData['slug']})";
                    continue;
                }

                SeoTemplate::updateOrCreate(
                    [
                        'target_model' => Location::class,
                        'target_id'    => $location->id,
                    ],
                    [
                        'meta_title'       => $govData['meta_title'],
                        'meta_description' => mb_substr($govData['meta_description'], 0, 320, 'UTF-8'),
                        'keywords'         => $govData['keywords'],
                        'og_image'         => "/images/seo/governorates/{$govData['slug']}.jpg",
                        'canonical_url'    => null,
                        'schema_markup'    => null,
                    ]
                );

                $inserted++;
                $this->command->line("  ✅ {$govData['name_ar']}");

            } catch (\Throwable $e) {
                $errors[] = "❌ خطأ في {$govData['name_ar']}: " . $e->getMessage();
                $this->command->error("  ❌ خطأ في {$govData['name_ar']}: " . $e->getMessage());
            }
        }

        // عرض الإحصائيات النهائية
        $this->command->newLine();
        $this->command->info("📊 إحصائيات زرع بيانات SEO:");
        $this->command->info("   ✅ تم إدراج/تحديث: {$inserted} محافظة");

        if ($skipped > 0) {
            $this->command->warn("   ⚠️  تم تخطي: {$skipped} محافظة (غير موجودة في جدول locations)");
            $this->command->warn("   💡 تلميح: قم بتشغيل LocationSeeder أولاً: php artisan db:seed --class=LocationSeeder");
        }

        foreach ($errors as $error) {
            $this->command->warn("   {$error}");
        }

        if ($inserted > 0) {
            $this->command->newLine();
            $this->command->info("🎉 تم بنجاح! {$inserted} سجل SEO جاهز للمحافظات المصرية.");
            $this->command->info("🖼️  لتوليد صور SEO شغّل: php artisan nilex:generate-seo-images");
        }
    }
